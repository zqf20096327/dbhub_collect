# -*- coding: utf-8 -*-
"""T5b release notes 复验触发器（2026-11-04）。

适配是活结论：release notes 命中 add/drop/support/deprecate + 库名 → 该仓
适配结论可能过期，进复验队列。口径（[[attribution-evidence-layer]] 定案吸收）：
宽匹配（行内提到库名即收）+ 四动词强度排序（add > support > deprecate > drop）
+ 去模板头部（Keep a Changelog 类样板行不产出）。

词表 = attribution.vocab.readme_vocab()（与 db_scan 同源，零新词表）。
零网络纯函数；队列落盘 state/relnotes_queue.json（atomic LF）。
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from attribution.vocab import readme_vocab          # noqa: E402

OUT = ROOT / "state" / "relnotes_queue.json"

# 四动词词形族（add/drop/support/deprecate；强度序=列表序）
VERBS = {
    "add":       r"add(?:ed|s|ing)?",
    "support":   r"support(?:ed|s|ing)?|support\s+for",
    "deprecate": r"deprecat(?:ed|es|ing|ion)",
    "drop":      r"drop(?:ped|ping|s)?|remov(?:ed|es|ing|al)|discontinu(?:ed|es|ing|ation)",
}
_VERB_RE = re.compile("|".join(rf"(?P<{k}>{v})" for k, v in VERBS.items()), re.I)

# Keep a Changelog / 自动生成类样板行（去模板头部：不产出、不引证）
_TEMPLATE_RE = re.compile(
    r"^(all notable changes|this (file|changelog)|the format is based on|"
    r"this project adheres to|generated by|auto[- ]generated|"
    r"<!—|<!--|see the full changelog)", re.I)

_VOCAB: dict[str, list[str]] | None = None


def _vocab() -> dict[str, list[str]]:
    global _VOCAB
    if _VOCAB is None:
        _VOCAB = readme_vocab()
    return _VOCAB


def _db_hits(line_lower: str) -> list[str]:
    """行内命中的 17 库（词边界；短词如 pg 已在词表里显式列出）。"""
    out = []
    for db, words in _vocab().items():
        for w in words:
            if re.search(rf"(?<![a-z0-9]){re.escape(w)}(?![a-z0-9])", line_lower):
                out.append(db)
                break
    return out


def parse(text: str) -> list[dict]:
    """release notes 文本 → hits（db/verb/quote/line，动词强度降序）。"""
    hits: list[dict] = []
    for i, line in enumerate(text.splitlines(), 1):
        s = line.strip()
        if not s or _TEMPLATE_RE.match(s):
            continue
        low = s.lower()
        m = _VERB_RE.search(low)
        if not m:
            continue
        verb = next(k for k, v in m.groupdict().items() if v)
        for db in _db_hits(low):
            hits.append({"db": db, "verb": verb, "line": i, "quote": s[:120]})
    hits.sort(key=lambda h: list(VERBS).index(h["verb"]))
    return hits


def trigger(fn: str, text: str, at: str | None = None) -> list[dict]:
    """单仓 release notes → 队列条目（同库多命中取最强动词）。"""
    best: dict[str, dict] = {}
    for h in parse(text):
        cur = best.get(h["db"])
        if cur is None or list(VERBS).index(h["verb"]) < list(VERBS).index(cur["verb"]):
            best[h["db"]] = h
    return [{"fn": fn, "db": db, "verb": h["verb"], "quote": h["quote"],
             "line": h["line"], "at": at or datetime.now().strftime("%Y-%m-%d")}
            for db, h in best.items()]


def main() -> int:
    ap = argparse.ArgumentParser(description="T5b release notes 复验触发器")
    ap.add_argument("--file", help="markdown 文件路径")
    ap.add_argument("--text", help="直接给文本")
    ap.add_argument("--fn", default="test/repo", help="仓名（写队列用）")
    ap.add_argument("--report-only", action="store_true", help="只解析打印不写队列")
    args = ap.parse_args()
    text = args.text or (Path(args.file).read_text(encoding="utf-8")
                         if args.file else "")
    if not text:
        raise SystemExit("--file 或 --text 至少一个")
    hits = trigger(args.fn, text)
    for h in hits:
        print(f"[{h['verb']:>9}] {h['db']:<12} L{h['line']}: {h['quote'][:100]}")
    print(f"共 {len(hits)} 条命中")
    if not args.report_only:
        q = json.loads(OUT.read_text(encoding="utf-8")) if OUT.is_file() else {}
        for h in hits:
            q.setdefault(h["fn"], []).append(h)
        tmp = OUT.with_name(OUT.name + ".tmp")
        tmp.write_text(json.dumps(q, ensure_ascii=False), encoding="utf-8", newline="\n")
        tmp.replace(OUT)
        print(f"队列 {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
