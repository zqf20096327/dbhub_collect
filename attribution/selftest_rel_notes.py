# -*- coding: utf-8 -*-
"""T5b 离线自检：合成 release note 5 条 + 模板头部/边界/强度排序。零网络零 API。

跑法：python attribution/selftest_rel_notes.py（退出码 0=全绿）
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from attribution import rel_notes as R    # noqa: E402

fails: list[str] = []


def ck(cond, name: str) -> None:
    print(f"[{'PASS' if cond else 'FAIL'}] {name}")
    if not cond:
        fails.append(name)


def dbs(hits, verb=None):
    return {h["db"] for h in hits if verb is None or h["verb"] == verb}


def main() -> int:
    # 1) 合成五条（卡文验收）：add MySQL / drop PG / support Oracle+SS /
    #    无动词纯提及不命中 / deprecate 命中
    h = R.parse("Added MySQL 8 support for the new engine")
    ck("MySQL" in dbs(h, "add") and len(h) == 1, "add+MySQL 命中")

    h = R.parse("Dropped PostgreSQL support in v3")
    ck("PostgreSQL" in dbs(h, "drop") and len(h) == 1, "drop+PostgreSQL 命中")

    h = R.parse("Add support for Oracle RAC and SQL Server")
    ck(dbs(h) == {"Oracle", "SQL Server"} and all(x["verb"] == "add" for x in h),
       "add 双库命中（Oracle+SQL Server）")

    h = R.parse("The MySQL connection pool now uses async I/O")
    ck(h == [], "纯提及无动词不命中")

    h = R.parse("- Deprecated the legacy MySQL adapter\n- Added support for TiDB")
    ck("MySQL" in dbs(h, "deprecate") and "TiDB" in dbs(h, "add"), "deprecate+add 分动词命中")

    # 2) 模板头部不产出（Keep a Changelog 样板 + HTML 注释）
    tmpl = ("# Changelog\n\nAll notable changes to this project will be documented "
            "in this file.\nThe format is based on Keep a Changelog.\n"
            "<!-- generated by release-please -->\n\nAdded MariaDB support.\n")
    h = R.parse(tmpl)
    ck(h == [x for x in h if x["db"] == "MariaDB"] and len(h) == 1
       and "Keep a Changelog" not in h[0]["quote"], "模板头部不产出、真命中保留")

    # 3) 词表别名（sqlite3）与词边界（mysql 不匹配 mysqltool）
    ck("SQLite" in dbs(R.parse("supports sqlite3 in-memory mode"), "support"),
       "sqlite3 别名命中 SQLite")
    ck(R.parse("uses mysqltool for deployment") == [], "词边界：mysqltool 不误伤 MySQL")

    # 4) 强度排序：同库 add+drop 分列两行 → 排序 add 在前；trigger 每库取最强
    mixed = "- Dropped SQLite journal mode\n- Added SQLite WAL support"
    hs = R.parse(mixed)
    ck([x["verb"] for x in hs] == ["add", "drop"], "强度排序 add 先于 drop")
    t = R.trigger("t/repo", mixed)
    ck(len(t) == 1 and t[0]["verb"] == "add" and t[0]["db"] == "SQLite",
       "trigger 同库多命中取最强")

    verdict = "PASS" if not fails else "FAIL"
    print(f"[{verdict}] T5b release notes 触发器：合成 5 条 + 模板头部 + 别名/词边界"
          f" + 强度排序（{len(fails)} 失败）")
    for f in fails:
        print(f)
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
